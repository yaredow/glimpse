#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import postcss from "postcss";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

export const DEFAULT_CSS_PATH = path.join(root, "global.css");
export const DEFAULT_OUT_PATH = path.join(root, "lib", "theme", "tokens.generated.ts");

const TRIPLET = /^([0-9.]+)\s+([0-9.]+)%\s+([0-9.]+)%$/;

/** The same conversion React Native's colour parser performs. */
export function hslToRgb(h, s, l) {
  s /= 100;
  l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) =>
    l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
}

export function rgbToHex([r, g, b]) {
  return (
    "#" +
    [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("").toUpperCase()
  );
}

/** `"240 7.7% 5.1%"` -> `"#0C0C0E"`; returns null for non-colour values. */
export function hslTripletToHex(value) {
  const match = TRIPLET.exec(value.trim());
  if (!match) return null;
  return rgbToHex(hslToRgb(Number(match[1]), Number(match[2]), Number(match[3])));
}

/** `--error-container-foreground` -> `errorContainerForeground` */
export function cssVarToKey(prop) {
  return prop
    .replace(/^--/, "")
    .split("-")
    .filter(Boolean)
    .map((part, index) => {
      if (/^[0-9]+$/.test(part)) return part;
      return index === 0 ? part : part[0].toUpperCase() + part.slice(1);
    })
    .join("");
}

export function parseColorTokens(cssText) {
  const tokens = [];
  const seen = new Map();

  postcss.parse(cssText).walkRules((rule) => {
    if (rule.selector.trim() !== ":root") return;
    rule.walkDecls((decl) => {
      if (!decl.prop.startsWith("--")) return;
      const hex = hslTripletToHex(decl.value);
      if (!hex) return; // e.g. --radius
      const key = cssVarToKey(decl.prop);
      if (seen.has(key)) {
        throw new Error(
          `Duplicate token key "${key}" from ${seen.get(key)} and ${decl.prop}`,
        );
      }
      seen.set(key, decl.prop);
      tokens.push({ prop: decl.prop, key, hex: hex.toUpperCase() });
    });
  });

  if (tokens.length === 0) {
    throw new Error("No colour tokens found in :root");
  }

  return tokens;
}

export function renderTokensModule(tokens) {
  const body = tokens.map(({ key, hex }) => `  ${key}: "${hex}",`).join("\n");
  return `// AUTO-GENERATED by scripts/gen-tokens.mjs — do not edit by hand.
// Source: app/global.css. Regenerate with \`bun run tokens:generate\`.

export const colors = {
${body}
} as const;

export type ColorToken = keyof typeof colors;
`;
}

/** JSON mirror for Node-time consumers such as app.config.ts. */
export function renderTokensJson(tokens) {
  const value = Object.fromEntries(tokens.map(({ key, hex }) => [key, hex]));
  return JSON.stringify(value, null, 2) + "\n";
}

export function generate({
  cssPath = DEFAULT_CSS_PATH,
  outPath = DEFAULT_OUT_PATH,
  jsonPath = outPath.replace(/\.ts$/, ".json"),
  check = false,
} = {}) {
  const tokens = parseColorTokens(fs.readFileSync(cssPath, "utf8"));
  const content = renderTokensModule(tokens);
  const jsonContent = renderTokensJson(tokens);

  if (check) {
    let current = null;
    let currentJson = null;
    try {
      current = fs.readFileSync(outPath, "utf8");
    } catch {
      current = null;
    }
    try {
      currentJson = fs.readFileSync(jsonPath, "utf8");
    } catch {
      currentJson = null;
    }
    return {
      ok: current === content && currentJson === jsonContent,
      tokens,
      content,
      jsonContent,
      current,
      currentJson,
    };
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, content);
  fs.writeFileSync(jsonPath, jsonContent);
  return {
    ok: true,
    tokens,
    content,
    jsonContent,
    current: content,
    currentJson: jsonContent,
  };
}

const entry = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : "";

if (entry === import.meta.url) {
  const check = process.argv.includes("--check");
  const result = generate({ check });

  if (check) {
    if (!result.ok) {
      console.error(
        `Generated tokens are stale (${result.tokens.length} tokens in global.css).`,
      );
      console.error("Run `bun run tokens:generate` and commit the result.");
      process.exit(1);
    }
    console.log(
      `Generated tokens are current (${result.tokens.length} tokens).`,
    );
  } else {
    console.log(
      `Wrote tokens.generated.ts + tokens.generated.json (${result.tokens.length} tokens).`,
    );
  }
}
