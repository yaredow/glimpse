import {
  BabyIcon,
  BookOpenIcon,
  CompassIcon,
  ConfettiIcon,
  CrosshairIcon,
  DetectiveIcon,
  FilmStripIcon,
  GhostIcon,
  HeartIcon,
  HorseIcon,
  LightningIcon,
  MagicWandIcon,
  MagnifyingGlassIcon,
  MusicNotesIcon,
  PaletteIcon,
  RocketIcon,
  SwordIcon,
  TelevisionIcon,
  UsersIcon,
  VideoIcon,
  type Icon,
} from "phosphor-react-native";

const GENRE_ICONS: Record<string, Icon> = {
  action: LightningIcon,
  adventure: CompassIcon,
  animation: PaletteIcon,
  biography: BookOpenIcon,
  comedy: ConfettiIcon,
  crime: DetectiveIcon,
  documentary: VideoIcon,
  drama: UsersIcon,
  family: BabyIcon,
  fantasy: MagicWandIcon,
  history: BookOpenIcon,
  horror: GhostIcon,
  music: MusicNotesIcon,
  mystery: MagnifyingGlassIcon,
  romance: HeartIcon,
  "science fiction": RocketIcon,
  "sci-fi": RocketIcon,
  "tv movie": TelevisionIcon,
  thriller: CrosshairIcon,
  war: SwordIcon,
  western: HorseIcon,
};

export const getGenreIcon = (name: string): Icon =>
  GENRE_ICONS[name.toLowerCase().trim()] ?? FilmStripIcon;
